/**
 * Scalable smart objects
 * ----------------------
 * Some decorations are naturally REPETITIVE: a breakable block is a single tile,
 * but a wall of breakable blocks is just that tile repeated sideways or
 * downwards. Placing twenty separate one-tile objects to build such a wall is
 * tedious and clutters the room's object list.
 *
 * A definition opts into scaling by carrying an {@link IScalable} descriptor.
 * The user then picks a direction from the context menu's **Scale** submenu, and
 * the placement grows one step in that direction. Scaling is stored on the
 * placement as a small {@link SmartObjectScale} record, so it stays **one single
 * smart object** — one row in the object list, one thing to move or delete —
 * while baking exactly the tiles it visually shows.
 *
 * Growth is expressed by repeating the definition's tiles: every tile of the
 * variant that lies on the edge facing the chosen direction is copied one step
 * further out. For a 1×1 object such as the breakable block that simply
 * duplicates the tile to the left/right/up/down, which is exactly the desired
 * behaviour for building walls; for a wider object the whole edge row/column is
 * repeated, which is the natural reading of "make it bigger in that direction".
 */

import { SmartObjectDefinition, SmartObjectTileOffset } from '../smartobject.definition';

/** The four directions a scalable object can grow in. */
export type ScaleDirection = 'north' | 'south' | 'west' | 'east';

/** All scale directions, in menu order (matching the compass). */
export const SCALE_DIRECTIONS: readonly ScaleDirection[] = ['north', 'south', 'west', 'east'];

/** Display labels for the scale directions. */
export const SCALE_DIRECTION_LABELS: Record<ScaleDirection, string> = {
  north: 'North',
  south: 'South',
  west: 'West',
  east: 'East',
};

/**
 * How far a placement has been grown in each direction, in tiles.
 *
 * All values are 0 (no growth) until the user picks a direction; negative
 * growth is never used.
 */
export interface SmartObjectScale {
  north: number;
  south: number;
  west: number;
  east: number;
}

/** Scaling behaviour of a smart object that can be grown. */
export interface IScalable {
  /**
   * Whether the object may grow in a given direction that pushes it outside the
   * room. Rooms clip anyway, so this is only ever used to keep the menu honest.
   */
  readonly maxSteps?: number;
}

/** A definition that carries scaling behaviour. */
export interface ScalableSmartObjectDefinition extends SmartObjectDefinition {
  /** Scaling descriptor, or undefined when the object cannot be grown. */
  scalable?: IScalable;
}

/** The scaling descriptor of a definition, when it can be grown. */
export function scalableOf(definition: SmartObjectDefinition | undefined): IScalable | undefined {
  return (definition as ScalableSmartObjectDefinition | undefined)?.scalable;
}

/** Whether a definition can be grown with the context menu's "Scale" feature. */
export function canScale(definition: SmartObjectDefinition | undefined): boolean {
  return scalableOf(definition) !== undefined;
}

/** A placement's scale, defaulting every direction to 0. */
export function scaleOf(scale: SmartObjectScale | undefined): SmartObjectScale {
  return {
    north: scale?.north ?? 0,
    south: scale?.south ?? 0,
    west: scale?.west ?? 0,
    east: scale?.east ?? 0,
  };
}

/** Whether a scale record actually grows the object in any direction. */
export function isScaled(scale: SmartObjectScale | undefined): boolean {
  if (!scale) {
    return false;
  }
  return scale.north > 0 || scale.south > 0 || scale.west > 0 || scale.east > 0;
}

/**
 * Grows a scale record one step in `direction`, clamped to `maxSteps`.
 *
 * @param scale Current scale (may be undefined).
 * @param direction Direction to grow in.
 * @param maxSteps Upper bound per direction (defaults to unbounded within the
 *   room's 32 tiles).
 */
export function growScale(
  scale: SmartObjectScale | undefined,
  direction: ScaleDirection,
  maxSteps = 31,
): SmartObjectScale {
  const current = scaleOf(scale);
  return { ...current, [direction]: Math.min(maxSteps, current[direction] + 1) };
}

/** Shrinks a scale record by one step in `direction` (never below 0). */
export function shrinkScale(
  scale: SmartObjectScale | undefined,
  direction: ScaleDirection,
): SmartObjectScale {
  const current = scaleOf(scale);
  return { ...current, [direction]: Math.max(0, current[direction] - 1) };
}

/** Resets a scale record to "no growth". */
export function resetScale(): SmartObjectScale {
  return { north: 0, south: 0, west: 0, east: 0 };
}

/**
 * Expands a variant's tile offsets by the given scale.
 *
 * Each screen of repeated tiles is generated by copying the tiles on the edge
 * facing the growth direction and translating them one step (2, 3, … steps for
 * further growth). Everything is expressed as ORDINARY tile offsets relative to
 * the placement anchor, so the rest of the editor (rendering, previews, ground
 * compositing, baking) needs no knowledge of scaling at all.
 *
 * @param tiles The variant's tile offsets.
 * @param scale Growth per direction.
 * @returns The tiles including every repeated copy.
 */
export function expandScaledTiles(
  tiles: readonly SmartObjectTileOffset[],
  scale: SmartObjectScale | undefined,
): SmartObjectTileOffset[] {
  const growth = scaleOf(scale);
  if (!isScaled(growth) || tiles.length === 0) {
    return [...tiles];
  }
  const result: SmartObjectTileOffset[] = [...tiles];
  // `seen` keeps the expansion idempotent: a tile can be produced by two
  // directions at a corner, and duplicates must not be stamped twice.
  const seen = new Set(tiles.map((tile) => `${tile.dRow},${tile.dCol}`));
  const push = (tile: SmartObjectTileOffset): void => {
    const key = `${tile.dRow},${tile.dCol}`;
    if (seen.has(key)) {
      return;
    }
    seen.add(key);
    result.push(tile);
  };

  // Growth works by repeating the WHOLE object one step further out, once per
  // requested step. Repeating the object (not just its edge tiles) is what
  // turns a wall into a filled rectangle: growing west "for a 1-tile block"
  // yields a row of blocks, and growing that row south yields a solid grid —
  // while a multi-tile object (say a 3×2 house) grows by cloning its own shape.
  //
  // Steps may RUN TOGETHER: growing west twice before growing south once must
  // produce the same result as growing south then west twice, so the loop below
  // expands against a growing set rather than a fixed edge.
  const north = (): void => {
    for (const tile of [...result]) {
      push({ ...tile, dRow: tile.dRow - 1 });
    }
  };
  const south = (): void => {
    for (const tile of [...result]) {
      push({ ...tile, dRow: tile.dRow + 1 });
    }
  };
  const west = (): void => {
    for (const tile of [...result]) {
      push({ ...tile, dCol: tile.dCol - 1 });
    }
  };
  const east = (): void => {
    for (const tile of [...result]) {
      push({ ...tile, dCol: tile.dCol + 1 });
    }
  };

  for (let step = 0; step < growth.north; step++) {
    north();
  }
  for (let step = 0; step < growth.south; step++) {
    south();
  }
  for (let step = 0; step < growth.west; step++) {
    west();
  }
  for (let step = 0; step < growth.east; step++) {
    east();
  }
  return result;
}
