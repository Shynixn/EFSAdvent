import { Injectable, inject } from '@angular/core';
import { LoggingService } from './logging.service';
import { FSALibService } from './fsalib.service';
import { EditorService } from './editor.service';
import { parseBti } from './render/bti-texture';
import { decodeTexture } from './render/bti-image';
import { ImageBuffer, TILE_SIZE } from './render/gba-tile-renderer';
import { ArchivePathResolver, StageRenderer } from './render/stage-renderer';
import { StageData } from '../entity/fsalib.entity';
import { ActorDefinition } from '../entity/actor-definition.entity';
import { tileForActor } from '../entity/tile-actor.entity';
import {
  ACTOR_SPRITE_CACHE_DIR,
  actorSpritePath,
} from '../entity/actor-sprite.entity';

/** Progress callback used while generating the sprite cache. */
export type SpriteProgress = (done: number, total: number, message: string) => void;

/**
 * ActorSpriteService
 * ------------------
 * Builds the actor-sprite cache **at ISO-import time** — nothing is shipped with
 * the app; every icon is produced from the game's extracted `data.arc`.
 *
 * Icons are written to `/editor/cache/image/actorsprite/<ACTOR_ID>.png` (the same
 * file the app reads back: `iconPathFor`). They are used only for actors whose
 * catalog definition has no `rendering` (the game draws those itself: switches,
 * warps, chests, properties…), plus templates whose actor cannot be drawn from
 * the stage's sprite sheets.
 *
 * HOW THE ICON IS CHOSEN (smart lookup), most specific first:
 * 1. **the tile that represents the actor** — `tileproperties.json` says which
 *    tiles imply an actor (`RequiredActorID`); e.g. tile 48 *is* the chest, so
 *    the `TKRA` icon is that tile drawn with the game's tileset,
 * 2. a texture referenced by the actor's own render variants (`BtiFile`),
 * 3. a `TIMG` texture whose file name matches the actor id
 *    (`<id>_*.bti` / `<id>.bti`, e.g. `WARP` → `warp_21.bti`),
 * 4. a texture whose name matches a distinctive token of the actor's display or
 *    internal name,
 * 5. a generated placeholder glyph (actor id in block letters on a
 *    category-coloured tile) so the toolbox never shows an empty card.
 *
 * The heuristics are deliberately conservative: a candidate must decode to an
 * image with actual opaque pixels, and the first hit wins.
 */
@Injectable({ providedIn: 'root' })
export class ActorSpriteService {
  private readonly logger = inject(LoggingService);
  private readonly fsaLib = inject(FSALibService);
  private readonly editor = inject(EditorService);

  /** Set while a generation run is in flight, so callers can await it. */
  private running: Promise<void> | null = null;

  /** Whether this run already produced the cache (idempotent per session). */
  private generated = false;

  /** Category colours for the generated placeholder glyphs. */
  private static readonly CATEGORY_COLORS: Record<string, [number, number, number]> = {
    TileObject: [76, 176, 225],
    Object: [129, 199, 132],
    Property: [255, 183, 77],
    NPC: [240, 98, 146],
    Item: [255, 213, 79],
    Special: [149, 117, 205],
    Default: [144, 164, 174],
  };

  /**
   * Generates the sprite cache for every actor that needs one.
   *
   * Idempotent: a second call while a run is in flight joins it, and a completed
   * run is skipped. Failures are non-fatal (the toolbox falls back to its normal
   * rendering, then to a text-only card).
   */
  async ensureIcons(onProgress?: SpriteProgress): Promise<void> {
    if (this.generated) {
      return;
    }
    if (this.running) {
      return this.running;
    }
    this.running = this.generate(onProgress)
      .then(() => {
        this.generated = true;
      })
      .catch((error) => {
        this.logger.warn('ActorSpriteService: icon generation failed (non-fatal)', error);
      })
      .finally(() => {
        this.running = null;
      });
    return this.running;
  }

  /** True when an icon exists for `actorId` (whether or not it has content). */
  hasIcon(actorId: string): boolean {
    return this.written.has(actorId.toUpperCase());
  }

  /**
   * Resolves the icon path for an actor, checking the editor store so icons
   * generated by an earlier session (i.e. at ISO import) are still found.
   * Cached per actor; returns null when no icon exists.
   */
  async iconPathFor(actorId: string): Promise<string | null> {
    const id = actorId.toUpperCase();
    const cached = this.pathCache.get(id);
    if (cached !== undefined) {
      return cached;
    }
    const path = actorSpritePath(id);
    const exists = this.written.has(id)
      ? true
      : await this.editor.hasEditorFile(path).catch(() => false);
    this.pathCache.set(id, exists ? path : null);
    if (exists) {
      this.written.add(id);
    }
    return exists ? path : null;
  }

  /** Resolved icon paths (null = no icon), so lookups hit the store only once. */
  private readonly pathCache = new Map<string, string | null>();

  /** Editor-store path of an already-generated icon, or null. */
  iconPath(actorId: string): string | null {
    const id = actorId.toUpperCase();
    return this.written.has(id) ? actorSpritePath(id) : null;
  }

  /** Ids written during this run (also used by `hasIcon`). */
  private readonly written = new Set<string>();

  /** Performs the actual generation. */
  private async generate(onProgress?: SpriteProgress): Promise<void> {
    onProgress?.(0, 1, 'Reading game data…');
    const dataArc = await this.fsaLib.dataArc();
    if (!dataArc) {
      this.logger.warn('ActorSpriteService: data.arc is not extracted; skipping sprite icons.');
      return;
    }

    const actors = await this.fsaLib.loadActors();
    // Actors that cannot be rendered from the catalog are the ones needing an icon.
    const missing = Object.values(actors).filter(
      (definition) => (definition.Rendering ?? []).length === 0,
    );
    if (missing.length === 0) {
      return;
    }

    onProgress?.(0, missing.length, 'Indexing actor textures…');
    const textures = await this.indexTextures(dataArc);
    const tileActors = await this.fsaLib.loadTileActors();
    const tileRenderer = await this.openTileRenderer(dataArc);

    let done = 0;
    for (const definition of missing) {
      const id = definition.Id.toUpperCase();
      try {
        // 1. The tile the game uses for this actor (authoritative).
        const tile = tileForActor(id, tileActors);
        const tileIcon = tile && tileRenderer ? this.drawTile(tileRenderer, tile.tile) : null;
        const image =
          tileIcon ?? (await this.pickIcon(definition, dataArc, textures));
        const icon = image ?? this.placeholder(definition);
        const png = this.encodePng(icon);
        await this.editor.writeEditorFile(actorSpritePath(id), png);
        this.written.add(id);
      } catch (error) {
        this.logger.warn(`ActorSpriteService: failed to build icon for ${id}`, error);
      }
      done++;
      if (done % 20 === 0) {
        onProgress?.(done, missing.length, `Generating actor sprites… ${done}/${missing.length}`);
      }
    }

    this.logger.info(
      `ActorSpriteService: generated ${this.written.size}/${missing.length} actor sprite icon(s) in /editor/${ACTOR_SPRITE_CACHE_DIR}.`,
    );
    onProgress?.(missing.length, missing.length, 'Actor sprites ready');
  }

  /**
   * Opens a throwaway {@link StageRenderer} used to draw tileset tiles.
   *
   * Tileset graphics come from `data.arc`; the tileset is fixed to the level-1
   * default (`TILE_ICON_TILESHEET`) because the icon cache is global, not
   * per-stage. Only `init()` + `prepareTileset()` are needed — no rooms.
   */
  private async openTileRenderer(dataArc: Uint8Array): Promise<StageRenderer | null> {
    try {
      const stage = {
        Index: 1,
        Map: {
          Index: 1,
          XDimension: 8,
          YDimension: 8,
          EmptyRoomValue: -1,
          StartX: 0,
          StartY: 0,
          TileSheetId: ActorSpriteService.TILE_ICON_TILESHEET,
          NpcSheetId: 0,
          Rooms: [],
        },
        MapSingleplayer: null,
        Rooms: [],
        Actors: [],
        Resources: { Directories: {} },
      } as unknown as StageData;

      const renderer = new StageRenderer(
        stage,
        async (path) => this.fsaLib.readArchiveFile(dataArc, path),
        new ArchivePathResolver(await this.fsaLib.dataArcFilePaths()),
        await this.fsaLib.loadTilesets(),
        await this.fsaLib.loadActors(),
      );
      await renderer.init();
      await renderer.prepareTileset();
      return renderer;
    } catch (error) {
      this.logger.warn('ActorSpriteService: could not open a tileset renderer', error);
      return null;
    }
  }

  /**
   * Draws one tileset tile into a 16×16 icon (null when the tile is blank).
   *
   * Uses {@link StageRenderer.drawTilesetTile}, so the result is exactly what the
   * room canvas would show for that tile.
   */
  private drawTile(renderer: StageRenderer, tile: number): ImageBuffer | null {
    try {
      const image = new ImageBuffer(TILE_SIZE, TILE_SIZE);
      renderer.drawTilesetTile(image, 0, 0, tile);
      return this.hasContent(image) ? image : null;
    } catch {
      return null;
    }
  }

  /** Tileset used for the generated tile icons (level 1's default). */
  private static readonly TILE_ICON_TILESHEET = 0;

  /** Texture path index: lower-case bare file name → archive path. */  private async indexTextures(dataArc: Uint8Array): Promise<Map<string, string>> {
    const index = new Map<string, string>();
    let files: { Path: string; Name: string }[] = [];
    try {
      files = await this.fsaLib.listArchiveTextures(dataArc);
    } catch (error) {
      this.logger.warn('ActorSpriteService: failed to list data.arc textures', error);
      return index;
    }
    for (const file of files) {
      const bare = (file.Name || file.Path.split('/').pop() || '').toLowerCase();
      if (!index.has(bare)) {
        index.set(bare, file.Path);
      }
    }
    this.logger.info(`ActorSpriteService: indexed ${index.size} texture(s) from data.arc.`);
    return index;
  }

  /**
   * Chooses an icon for an actor: its own BTI variants first, then a texture
   * named after the actor, then a texture named after its display name.
   */
  private async pickIcon(
    definition: ActorDefinition,
    dataArc: Uint8Array,
    textures: Map<string, string>,
  ): Promise<ImageBuffer | null> {
    // 1. A texture the actor's own definition points at.
    const referenced = new Set<string>();
    for (const key of definition.Rendering ?? []) {
      for (const variant of key.Variants) {
        if (variant.BtiFile) {
          referenced.add(variant.BtiFile.toLowerCase());
        }
      }
    }
    for (const name of referenced) {
      const image = await this.readTexture(dataArc, textures, name);
      if (image) {
        return image;
      }
    }

    // 2. A texture named after the actor id (`pont_0.bti` for `PONT`).
    const id = definition.Id.toLowerCase();
    const byId = await this.readFirstTexture(dataArc, textures, (name) => name.startsWith(`${id}_`) ||
      name === `${id}.bti`);
    if (byId) {
      return byId;
    }

    // 3. A texture named after a distinctive token of its display/internal name.
    const tokens = this.nameTokens(definition);
    for (const token of tokens) {
      const image = await this.readFirstTexture(
        dataArc,
        textures,
        (name) => name.startsWith(`${token}_`) || name.startsWith(token),
      );
      if (image) {
        return image;
      }
    }

    return null;
  }

  /** Reads a texture by bare name (when known to exist in the index). */
  private async readTexture(
    dataArc: Uint8Array,
    textures: Map<string, string>,
    bareName: string,
  ): Promise<ImageBuffer | null> {
    const path = textures.get(bareName.toLowerCase());
    if (!path) {
      return null;
    }
    try {
      const bytes = await this.fsaLib.readArchiveFile(dataArc, path);
      const image = decodeTexture(parseBti(bytes));
      return this.hasContent(image) ? image : null;
    } catch {
      return null;
    }
  }

  /** Reads the first indexed texture matching `predicate` that has content. */
  private async readFirstTexture(
    dataArc: Uint8Array,
    textures: Map<string, string>,
    predicate: (bareName: string) => boolean,
  ): Promise<ImageBuffer | null> {
    for (const [bare, path] of textures) {
      if (!predicate(bare)) {
        continue;
      }
      try {
        const bytes = await this.fsaLib.readArchiveFile(dataArc, path);
        const image = decodeTexture(parseBti(bytes));
        if (this.hasContent(image)) {
          return image;
        }
      } catch {
        // Try the next candidate.
      }
    }
    return null;
  }

  /** Whether an image has any visible (non-transparent) pixel. */
  private hasContent(image: ImageBuffer): boolean {
    const pixels = image.pixels;
    for (let i = 3; i < pixels.length; i += 4) {
      if (pixels[i] > 0) {
        return true;
      }
    }
    return false;
  }

  /** Distinctive lower-case tokens of an actor's names, for texture matching. */
  private nameTokens(definition: ActorDefinition): string[] {
    const raw = `${definition.Id} ${definition.InternalName ?? ''}`;
    const tokens = raw
      .toLowerCase()
      .split(/[^a-z0-9]+/)
      .filter((token) => token.length >= 4);
    return [...new Set(tokens)];
  }

  /**
   * Builds a fallback glyph for actors the game draws itself: the actor id drawn
   * as block letters on a category-coloured tile, so the toolbox card is never
   * empty and stays identifiable.
   */
  private placeholder(definition: ActorDefinition): ImageBuffer {
    const size = 16;
    const image = new ImageBuffer(size, size);
    const [r, g, b] = ActorSpriteService.CATEGORY_COLORS[definition.Category] ??
      ActorSpriteService.CATEGORY_COLORS['Default'];

    // Filled tile with a 1px darker border.
    for (let y = 0; y < size; y++) {
      for (let x = 0; x < size; x++) {
        const edge = x === 0 || y === 0 || x === size - 1 || y === size - 1;
        image.set(x, y, edge ? Math.round(r * 0.55) : r, edge ? Math.round(g * 0.55) : g,
          edge ? Math.round(b * 0.55) : b, 255);
      }
    }

    // The actor id as tiny 3x5 block letters (2 letters fit the 16px tile).
    const letters = definition.Id.toUpperCase().slice(0, 2);
    for (let index = 0; index < letters.length; index++) {
      const glyph = ActorSpriteService.GLYPHS[letters[index]] ?? ActorSpriteService.GLYPHS['?'];
      const ox = 2 + index * 6;
      for (let row = 0; row < glyph.length; row++) {
        for (let col = 0; col < 3; col++) {
          if (glyph[row][col] === '1') {
            image.set(ox + col, 6 + row, 255, 255, 255, 255);
          }
        }
      }
    }
    return image;
  }

  /** Encodes an image as PNG bytes (lossless RGBA). */
  private encodePng(image: ImageBuffer): Uint8Array {
    const dataUrl = this.fsaLib.encodePng(image);
    const base64 = dataUrl.substring(dataUrl.indexOf(',') + 1);
    const binary = atob(base64);
    const bytes = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i++) {
      bytes[i] = binary.charCodeAt(i);
    }
    return bytes;
  }

  /** 3×5 block glyphs for the placeholder ids. */
  private static readonly GLYPHS: Record<string, string[]> = {
    A: ['010', '101', '111', '101', '101'],
    B: ['110', '101', '110', '101', '110'],
    C: ['011', '100', '100', '100', '011'],
    D: ['110', '101', '101', '101', '110'],
    E: ['111', '100', '110', '100', '111'],
    F: ['111', '100', '110', '100', '100'],
    G: ['011', '100', '101', '101', '011'],
    H: ['101', '101', '111', '101', '101'],
    I: ['111', '010', '010', '010', '111'],
    J: ['001', '001', '001', '101', '010'],
    K: ['101', '101', '110', '101', '101'],
    L: ['100', '100', '100', '100', '111'],
    M: ['101', '111', '111', '101', '101'],
    N: ['101', '111', '111', '111', '101'],
    O: ['010', '101', '101', '101', '010'],
    P: ['110', '101', '110', '100', '100'],
    Q: ['010', '101', '101', '111', '011'],
    R: ['110', '101', '110', '101', '101'],
    S: ['011', '100', '010', '001', '110'],
    T: ['111', '010', '010', '010', '010'],
    U: ['101', '101', '101', '101', '111'],
    V: ['101', '101', '101', '101', '010'],
    W: ['101', '101', '111', '111', '101'],
    X: ['101', '101', '010', '101', '101'],
    Y: ['101', '101', '010', '010', '010'],
    Z: ['111', '001', '010', '100', '111'],
    '0': ['111', '101', '101', '101', '111'],
    '1': ['010', '110', '010', '010', '111'],
    '2': ['110', '001', '010', '100', '111'],
    '3': ['110', '001', '010', '001', '110'],
    '4': ['101', '101', '111', '001', '001'],
    '5': ['111', '100', '110', '001', '110'],
    '6': ['011', '100', '111', '101', '111'],
    '7': ['111', '001', '010', '010', '010'],
    '8': ['111', '101', '111', '101', '111'],
    '9': ['111', '101', '111', '001', '110'],
    '?': ['110', '001', '010', '000', '010'],
  };
}
